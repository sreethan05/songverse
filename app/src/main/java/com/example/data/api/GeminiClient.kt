        Log.i(TAG, "Gemini AI disabled — fetchSongFromAI returning null for query: $query")
        return null
    }

    /**
     * Parses a playlist link or text from other apps using Gemini AI.
     * If a link is provided, it intelligently identifies or synthesizes a list of songs matching the platform or playlist style, 
     * complete with lyrics, genre, and trivia.
     */
    suspend fun parsePlaylistWithAI(source: String, input: String): GeminiPlaylistJson? {
        Log.i(TAG, "Gemini AI disabled — parsePlaylistWithAI returning null for source: $source")
        return null
    }

    /**
     * Fetch detailed artist biography, song backstory, and release details using Gemini AI.
     */
    suspend fun fetchDetailedSongInfo(title: String, artist: String, album: String, releaseYear: String): GeminiDetailedSongInfo? {
        Log.i(TAG, "Gemini AI disabled — fetchDetailedSongInfo returning fallback for $title by $artist")
        return null
    }
}
